  /* helpers used across pages */
  window.CAT_BY_ID = {};
  window.CATEGORIES.forEach(function (c) { window.CAT_BY_ID[c.id] = c; });
  window.TOOL_BY_SLUG = {};
  window.TOOLS.forEach(function (t) { window.TOOL_BY_SLUG[t.slug] = t; });
  window.toolsByCategory = function (cat) {
    return window.TOOLS.filter(function (t) { return t.cat === cat; });
  };
  window.popularTools = function (n) {
    return window.TOOLS.filter(function (t) { return t.popular; }).slice(0, n || 8);
  };
  window.searchTools = function (q, limit) {
    q = (q || "").trim().toLowerCase();
    if (!q) return [];
    var terms = q.split(/\s+/).filter(Boolean);
    var scored = [];
    window.TOOLS.forEach(function (t) {
      var name = t.name.toLowerCase(), cat = window.CAT_BY_ID[t.cat].name.toLowerCase();
      var hay = (name + " " + t.desc.toLowerCase() + " " + t.kw + " " + cat);
      var score = 0;
      terms.forEach(function (term) {
        if (name.indexOf(term) === 0) score += 12;
        else if (name.indexOf(term) > -1) score += 6;
        if (hay.indexOf(term) > -1) score += 3;
        if (t.kw.indexOf(term) > -1) score += 2;
      });
      if (score > 0 && t.popular) score += 0.5;
      if (score > 0) scored.push({ t: t, s: score });
    });
    scored.sort(function (a, b) { return b.s - a.s; });
    return scored.slice(0, limit || 12).map(function (x) { return x.t; });
  };
  window.fmtInt = function (n) { return n.toLocaleString("en-US"); };
